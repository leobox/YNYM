#!/usr/bin/env node
/**
 * sync-postgres.mjs — backlog.json 데이터를 PostgreSQL로 동기화하는 도구.
 *
 * 외부 npm 패키지 의존성 없이 순수 Node.js로 동작합니다.
 * 1. backlog.json을 읽어 UPSERT SQL 스크립트를 생성합니다.
 * 2. 실행 중인 leobox-postgres Docker 컨테이너가 있으면 psql로 직접 전달하여 동기화합니다.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const BACKLOG_FILE = resolve(ROOT, "backlog.json");
const SQL_OUTPUT = resolve(ROOT, "infra", "monitoring", "sync.sql");

function escapeSql(val) {
  if (val === null || val === undefined) return "NULL";
  if (typeof val === "number") return val;
  if (Array.isArray(val)) {
    if (val.length === 0) return "ARRAY[]::TEXT[]";
    const escapedItems = val.map(s => `'${String(s).replace(/'/g, "''")}'`).join(",");
    return `ARRAY[${escapedItems}]`;
  }
  return `'${String(val).replace(/'/g, "''")}'`;
}

function generateSql(data) {
  const statements = [
    "-- Auto-generated by tools/sync-postgres.mjs",
    "BEGIN;",
  ];

  for (const t of data.tasks) {
    statements.push(`
INSERT INTO tasks (
  id, title, summary, doc, status, priority, category, phase, estimate_min, where_path, deps, note, done_at, updated_at
) VALUES (
  ${escapeSql(t.id)},
  ${escapeSql(t.title)},
  ${escapeSql(t.summary)},
  ${escapeSql(t.doc)},
  ${escapeSql(t.status)},
  ${escapeSql(t.priority)},
  ${escapeSql(t.category)},
  ${escapeSql(t.phase)},
  ${escapeSql(t.estimate_min || 30)},
  ${escapeSql(t.where)},
  ${escapeSql(t.deps || [])},
  ${escapeSql(t.note)},
  ${escapeSql(t.done_at)},
  ${escapeSql(t.updated_at)}
)
ON CONFLICT (id) DO UPDATE SET
  title = EXCLUDED.title,
  summary = EXCLUDED.summary,
  doc = EXCLUDED.doc,
  status = EXCLUDED.status,
  priority = EXCLUDED.priority,
  category = EXCLUDED.category,
  phase = EXCLUDED.phase,
  estimate_min = EXCLUDED.estimate_min,
  where_path = EXCLUDED.where_path,
  deps = EXCLUDED.deps,
  note = EXCLUDED.note,
  done_at = EXCLUDED.done_at,
  updated_at = EXCLUDED.updated_at;
`);
  }

  statements.push("COMMIT;");
  return statements.join("\n");
}

function main() {
  if (!existsSync(BACKLOG_FILE)) {
    console.error(`오류: ${BACKLOG_FILE} 파일이 없습니다.`);
    process.exit(1);
  }

  const raw = readFileSync(BACKLOG_FILE, "utf-8");
  const data = JSON.parse(raw);
  const sql = generateSql(data);

  writeFileSync(SQL_OUTPUT, sql, "utf-8");
  console.log(`✓ SQL 생성 완료: ${SQL_OUTPUT} (총 ${data.tasks.length}개 작업)`);

  // Docker 컨테이너 leobox-postgres 실행 여부 확인
  try {
    const running = execSync("docker ps --filter name=leobox-postgres --format {{.Names}}", { encoding: "utf-8" }).trim();
    if (running.includes("leobox-postgres")) {
      console.log("⚡ 실행 중인 leobox-postgres 컨테이너 감지. 데이터베이스에 반영 중...");
      execSync(`docker exec -i leobox-postgres psql -U leobox -d leobox_backlog < "${SQL_OUTPUT}"`, { stdio: "inherit" });
      console.log("✓ PostgreSQL 동기화 완료!");
    } else {
      console.log("ℹ️  leobox-postgres 컨테이너가 실행 중이지 않습니다.");
      console.log("   (컨테이너 시작: cd infra/monitoring && docker compose up -d)");
    }
  } catch (e) {
    console.log("ℹ️  PostgreSQL 자동 적용 생략 (Docker 상태 확인 필요): " + e.message);
  }
}

main();
